package sdlc

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode/utf8"
)

const (
	BootstrapRendererVersion = "noise-sdlc-bootstrap@0.1"
	BootstrapFilename        = "BOOTSTRAP.md"
	BootstrapReceiptPath     = ".sdlc/bootstrap.json"
	BootstrapBlockBegin      = "<!-- noise-sdlc-bootstrap:begin -->"
	BootstrapBlockEnd        = "<!-- noise-sdlc-bootstrap:end -->"
)

type bootstrapReceipt struct {
	SchemaVersion int               `json:"schemaVersion"`
	Renderer      string            `json:"renderer"`
	Status        string            `json:"status"`
	Outputs       map[string]string `json:"outputs"`
	AgentsCreated bool              `json:"agentsCreated"`
}

type bootstrapState struct {
	receipt       bootstrapReceipt
	receiptDigest string
}

type managedPathSnapshot struct {
	exists  bool
	info    os.FileInfo
	content []byte
}

type managedMutation struct {
	path   string
	backup string
	before managedPathSnapshot
	after  managedPathSnapshot
}

type transactionHook func(stage, path string) error

// Bootstrap seeds one-time, agent-visible adoption instructions without
// selecting policy, probing providers, or adopting the target.
func Bootstrap(target string) (map[string]any, error) {
	return bootstrapWithHook(target, nil)
}

func bootstrapWithHook(target string, hook transactionHook) (map[string]any, error) {
	target, _ = filepath.Abs(target)
	if err := validateBootstrapPaths(target); err != nil {
		return nil, err
	}
	if hasAdoptionState(target) {
		return nil, fmt.Errorf("target already has lifecycle state; run onboarding status")
	}
	state, err := inspectBootstrap(target)
	if err != nil {
		return nil, err
	}
	if state != nil {
		return bootstrapResult("already-bootstrapped", state), nil
	}
	if pathExists(filepath.Join(target, BootstrapFilename)) {
		return nil, fmt.Errorf("refusing to overwrite existing %s", BootstrapFilename)
	}
	root, err := os.OpenRoot(target)
	if err != nil {
		return nil, fmt.Errorf("cannot anchor bootstrap to project root: %w", err)
	}
	defer root.Close()
	guardedPaths := []string{
		"AGENTS.md", BootstrapFilename, BootstrapReceiptPath,
		"SDLC.md", ".sdlc/project.yaml", ".sdlc/adoption.json",
	}
	snapshots, err := snapshotManagedPaths(root, guardedPaths)
	if err != nil {
		return nil, err
	}
	if snapshots[BootstrapFilename].exists || snapshots[BootstrapReceiptPath].exists {
		return nil, fmt.Errorf("bootstrap state changed during inspection; retry")
	}
	for _, relative := range []string{"SDLC.md", ".sdlc/project.yaml", ".sdlc/adoption.json"} {
		if snapshots[relative].exists {
			return nil, fmt.Errorf("target already has lifecycle state; run onboarding status")
		}
	}

	var existingAgents []byte
	agentsCreated := !snapshots["AGENTS.md"].exists
	if !agentsCreated {
		existingAgents = snapshots["AGENTS.md"].content
		if !utf8.Valid(existingAgents) {
			return nil, fmt.Errorf("cannot preserve AGENTS.md: content is not valid UTF-8")
		}
	}
	bootstrapBytes := renderBootstrapDocument()
	block := renderBootstrapAgentsBlock(DigestBytes(bootstrapBytes))
	agentsBytes, err := spliceBootstrapAgents(existingAgents, block)
	if err != nil {
		return nil, err
	}
	receipt := bootstrapReceipt{
		SchemaVersion: 1,
		Renderer:      BootstrapRendererVersion,
		Status:        "pending",
		Outputs: map[string]string{
			BootstrapFilename: DigestBytes(bootstrapBytes),
			"AGENTS.block":    DigestBytes([]byte(block)),
		},
		AgentsCreated: agentsCreated,
	}
	receiptBytes, err := CanonicalBytes(receipt)
	if err != nil {
		return nil, err
	}
	outputs := map[string][]byte{
		"AGENTS.md":          agentsBytes,
		BootstrapFilename:    bootstrapBytes,
		BootstrapReceiptPath: receiptBytes,
	}
	if err := writeBootstrapTransaction(root, target, outputs, snapshots, hook); err != nil {
		return nil, err
	}
	state = &bootstrapState{receipt: receipt, receiptDigest: DigestBytes(receiptBytes)}
	return bootstrapResult("bootstrapped", state), nil
}

func renderBootstrapDocument() []byte {
	return []byte(strings.Join([]string{
		"# Noise SDLC onboarding",
		"",
		"This is a one-time onboarding file generated by `noise sdlc bootstrap`.",
		"It does not adopt a lifecycle, connect Deck, launch a provider, or authorize spend.",
		"",
		"Before changing this repository:",
		"",
		"1. Read the repository's existing requirements, ADRs, and agent instructions.",
		"2. Run `noise sdlc onboarding status --target .` and stop for repair if instructed.",
		"3. Ask the operator for authorship, delivery, risk, routing preference, and any named high-risk classes. Record them in an answers file following the tool's schema. Do not guess capability or entitlement declarations.",
		"4. Run `noise sdlc plan --target . --answers <file>`. Report every planned path, unresolved execution role and reason, selected route, warning, and rollback action.",
		"5. Obtain explicit approval for that exact plan before running `noise sdlc adopt --target . --answers <same-file> --yes`.",
		"6. Run `noise sdlc verify --target .`, inspect the diff, and run project checks. Commit, publication, Deck synchronization, provider execution, and spend need separate authority.",
		"",
		"Inventory may use only catalog-approved bounded probes. Never inspect credentials, provider configuration, authentication output, account identity, balances, quota, environment values, private transcripts, or hidden reasoning.",
		"",
		"A successful adoption consumes this unchanged file and replaces the temporary AGENTS.md onboarding block with the verified lifecycle block. If this file or its receipt is missing or modified, remain read-only and report the conflict instead of recreating or overwriting it.",
		"",
	}, "\n"))
}

func renderBootstrapAgentsBlock(documentDigest string) string {
	return strings.Join([]string{
		BootstrapBlockBegin,
		"# Noise SDLC onboarding (generated)",
		"",
		"Before changing this repository, read root `BOOTSTRAP.md` and follow its plan-first onboarding procedure.",
		"Expected bootstrap digest: `" + documentDigest + "`.",
		"If the bootstrap file or `.sdlc/bootstrap.json` is missing or modified, remain read-only and report the conflict. Do not recreate, overwrite, adopt, commit, publish, connect Deck, launch providers, or authorize spend.",
		BootstrapBlockEnd,
	}, "\n")
}

func spliceBootstrapAgents(existing []byte, block string) ([]byte, error) {
	if existing == nil {
		return []byte(block + "\n"), nil
	}
	text := string(existing)
	if strings.Contains(text, BlockBegin) || strings.Contains(text, BlockEnd) {
		return nil, fmt.Errorf("AGENTS.md already contains adopted lifecycle markers")
	}
	if strings.Contains(text, BootstrapBlockBegin) || strings.Contains(text, BootstrapBlockEnd) {
		return nil, fmt.Errorf("AGENTS.md has unverified bootstrap markers")
	}
	return []byte(block + "\n\n" + strings.TrimLeft(text, "\n")), nil
}

func stripBootstrapAgents(existing []byte) ([]byte, error) {
	text := string(existing)
	if !strings.HasPrefix(text, BootstrapBlockBegin) || strings.Count(text, BootstrapBlockBegin) != 1 || strings.Count(text, BootstrapBlockEnd) != 1 {
		return nil, fmt.Errorf("AGENTS.md must contain exactly one byte-zero bootstrap block")
	}
	finishRelative := strings.Index(text, BootstrapBlockEnd)
	if finishRelative < 0 {
		return nil, fmt.Errorf("AGENTS.md has malformed bootstrap markers")
	}
	finish := finishRelative + len(BootstrapBlockEnd)
	return []byte(strings.TrimLeft(text[finish:], "\n")), nil
}

func inspectBootstrap(target string) (*bootstrapState, error) {
	if err := validateBootstrapPaths(target); err != nil {
		return nil, err
	}
	agentsPath := filepath.Join(target, "AGENTS.md")
	documentPath := filepath.Join(target, BootstrapFilename)
	receiptPath := filepath.Join(target, BootstrapReceiptPath)
	agentsExists := pathExists(agentsPath)
	documentExists := pathExists(documentPath)
	receiptExists := pathExists(receiptPath)
	hasMarkers := false
	if agentsExists {
		agents, err := os.ReadFile(agentsPath)
		if err != nil {
			return nil, fmt.Errorf("cannot inspect AGENTS.md bootstrap block: %w", err)
		}
		hasMarkers = strings.Contains(string(agents), BootstrapBlockBegin) || strings.Contains(string(agents), BootstrapBlockEnd)
	}
	if !hasMarkers && !receiptExists {
		return nil, nil
	}
	if !agentsExists || !hasMarkers || !documentExists || !receiptExists {
		return nil, fmt.Errorf("bootstrap state is incomplete; refusing to recreate or overwrite it")
	}

	var receipt bootstrapReceipt
	if err := LoadJSON(receiptPath, &receipt); err != nil {
		return nil, fmt.Errorf("invalid bootstrap receipt: %w", err)
	}
	if receipt.SchemaVersion != 1 || receipt.Renderer != BootstrapRendererVersion || receipt.Status != "pending" || len(receipt.Outputs) != 2 {
		return nil, fmt.Errorf("unsupported bootstrap receipt")
	}
	document, err := os.ReadFile(documentPath)
	if err != nil {
		return nil, err
	}
	if DigestBytes(document) != receipt.Outputs[BootstrapFilename] {
		return nil, fmt.Errorf("bootstrap output drift: %s", BootstrapFilename)
	}
	agents, err := os.ReadFile(agentsPath)
	if err != nil {
		return nil, err
	}
	block, err := extractBootstrapBlock(agents)
	if err != nil {
		return nil, err
	}
	if DigestBytes(block) != receipt.Outputs["AGENTS.block"] {
		return nil, fmt.Errorf("bootstrap output drift: AGENTS.md block")
	}
	receiptBytes, err := os.ReadFile(receiptPath)
	if err != nil {
		return nil, err
	}
	return &bootstrapState{receipt: receipt, receiptDigest: DigestBytes(receiptBytes)}, nil
}

func extractBootstrapBlock(agents []byte) ([]byte, error) {
	text := string(agents)
	if !strings.HasPrefix(text, BootstrapBlockBegin) || strings.Count(text, BootstrapBlockBegin) != 1 || strings.Count(text, BootstrapBlockEnd) != 1 {
		return nil, fmt.Errorf("AGENTS.md must contain exactly one byte-zero bootstrap block")
	}
	finishRelative := strings.Index(text, BootstrapBlockEnd)
	if finishRelative < 0 {
		return nil, fmt.Errorf("AGENTS.md has malformed bootstrap markers")
	}
	finish := finishRelative + len(BootstrapBlockEnd)
	return []byte(text[:finish]), nil
}

func validateBootstrapPaths(target string) error {
	for _, relative := range []string{"AGENTS.md", BootstrapFilename, BootstrapReceiptPath} {
		if err := validateManagedPath(target, relative); err != nil {
			return err
		}
	}
	return nil
}

func hasAdoptionState(target string) bool {
	for _, relative := range []string{"SDLC.md", ".sdlc/project.yaml", ".sdlc/adoption.json"} {
		if pathExists(filepath.Join(target, relative)) {
			return true
		}
	}
	if agents, err := os.ReadFile(filepath.Join(target, "AGENTS.md")); err == nil {
		return strings.Contains(string(agents), BlockBegin) || strings.Contains(string(agents), BlockEnd)
	}
	return false
}

func writeBootstrapTransaction(root *os.Root, target string, outputs map[string][]byte, snapshots map[string]managedPathSnapshot, hook transactionHook) error {
	ordered := []string{"AGENTS.md", BootstrapFilename, BootstrapReceiptPath}
	mutations := make([]managedMutation, 0, len(ordered))
	for _, relative := range ordered {
		if err := ensureManagedSnapshots(root, snapshots); err != nil {
			return transactionFailure(root, mutations, fmt.Errorf("bootstrap rolled back after concurrent change: %w", err))
		}
		mutation, err := writeManagedPathGuarded(root, target, relative, outputs[relative], snapshots[relative], hook)
		if err != nil {
			return transactionFailure(root, mutations, fmt.Errorf("bootstrap rolled back after installation failure: %w", err))
		}
		mutations = append(mutations, mutation)
		snapshots[relative] = mutation.after
	}
	return finalizeManagedMutations(root, mutations)
}

func snapshotManagedPaths(root *os.Root, paths []string) (map[string]managedPathSnapshot, error) {
	snapshots := make(map[string]managedPathSnapshot, len(paths))
	for _, relative := range paths {
		snapshot, err := snapshotManagedPath(root, relative)
		if err != nil {
			return nil, err
		}
		snapshots[relative] = snapshot
	}
	return snapshots, nil
}

func snapshotManagedPath(root *os.Root, relative string) (managedPathSnapshot, error) {
	info, err := root.Lstat(relative)
	if os.IsNotExist(err) {
		return managedPathSnapshot{}, nil
	}
	if err != nil {
		return managedPathSnapshot{}, fmt.Errorf("cannot inspect %s: %w", relative, err)
	}
	if !info.Mode().IsRegular() {
		return managedPathSnapshot{}, fmt.Errorf("managed path must be a regular file: %s", relative)
	}
	content, err := root.ReadFile(relative)
	if err != nil {
		return managedPathSnapshot{}, fmt.Errorf("cannot read %s: %w", relative, err)
	}
	return managedPathSnapshot{exists: true, info: info, content: content}, nil
}

func ensureManagedSnapshots(root *os.Root, snapshots map[string]managedPathSnapshot) error {
	paths := make([]string, 0, len(snapshots))
	for relative := range snapshots {
		paths = append(paths, relative)
	}
	sort.Strings(paths)
	for _, relative := range paths {
		expected := snapshots[relative]
		current, err := snapshotManagedPath(root, relative)
		if err != nil {
			return err
		}
		if !managedSnapshotsEqual(current, expected) {
			return fmt.Errorf("managed path changed at write boundary: %s", relative)
		}
	}
	return nil
}

func managedSnapshotsEqual(current, expected managedPathSnapshot) bool {
	if current.exists != expected.exists {
		return false
	}
	return !current.exists || (os.SameFile(current.info, expected.info) && DigestBytes(current.content) == DigestBytes(expected.content))
}

func bootstrapResult(state string, bootstrap *bootstrapState) map[string]any {
	return map[string]any{
		"schemaVersion":   1,
		"state":           state,
		"renderer":        BootstrapRendererVersion,
		"paths":           []string{"AGENTS.md", BootstrapFilename, BootstrapReceiptPath},
		"bootstrapDigest": bootstrap.receipt.Outputs[BootstrapFilename],
		"warnings": []string{
			"Bootstrap is onboarding guidance only; it is not an adopted lifecycle or execution authorization.",
		},
	}
}
